package cmd

import (
	"context"
	"fmt"
	"time"

	"charm.land/huh/v2/spinner"
	"github.com/rs/zerolog/log"
	"github.com/soerenschneider/sc/internal/tui"
	"github.com/soerenschneider/sc/internal/vault"
	"github.com/soerenschneider/sc/pkg"
	"github.com/spf13/cobra"
)

const vaultAwsLeaseID = "lease-id"

var vaultAwsRevokeCredentialsCmd = &cobra.Command{
	Use:     "revoke-credentials",
	Aliases: []string{"revoke"},
	Short:   "Revoke AWS credentials generated by Vault",
	Long: `Revoke AWS credentials that have been generated using 'generate-credentials' before they expire.

The Vault lease of the credentials is read from the given profile of the AWS credentials file
(~/.aws/credentials) and revoked. Afterwards, the credentials are removed from the profile.
Alternatively, a lease can be revoked directly using --lease-id.

Revoking requires the 'update' capability on 'sys/leases/revoke/<lease-id>' in Vault, which can
be granted for the leases of a single role, e.g. 'sys/leases/revoke/aws/creds/<role>/*'.

Note: For iam_user credentials, Vault deletes the access key in AWS. Credentials of type
assumed_role or federation_token are STS session credentials, which AWS can not invalidate.
They remain valid until they expire, even after their lease has been revoked.`,
	Run: func(cmd *cobra.Command, args []string) {
		profileName := pkg.GetString(cmd, vaultAwsProfile)
		leaseID := pkg.GetString(cmd, vaultAwsLeaseID)
		force := pkg.MustGetBool(cmd, vaultForce)

		var profile *awsCredentialsProfile
		profiles, err := readAwsCredentialsProfiles(profileName)
		if err == nil {
			profile = &profiles[0]
		} else if leaseID == "" {
			log.Fatal().Err(err).Msg("could not read credentials")
		}

		if leaseID == "" {
			if profile.LeaseID == "" {
				log.Fatal().Msgf("profile %q holds no Vault lease id, credentials generated by older versions can be revoked using --%s", profileName, vaultAwsLeaseID)
			}
			leaseID = profile.LeaseID
		}
		// Only clean up the profile if it holds the credentials of the revoked lease.
		profileMatches := profile != nil && profile.LeaseID == leaseID

		if !force {
			if profileMatches {
				printAwsCredentialsProfile(*profile)
			} else {
				tui.PrintMapOutput(map[string]any{"lease_id": leaseID})
			}

			if tui.SelectInput("Really revoke these credentials?", []string{"no", "yes"}) != "yes" {
				log.Info().Msg("Aborted, credentials have not been revoked")
				return
			}
		}

		client := vault.MustAuthenticateClient(vault.MustBuildClient(cmd))

		ctx, cancel := context.WithTimeout(context.Background(), vaultDefaultTimeout)
		defer cancel()

		if err := spinner.New().
			ActionWithErr(func(ctx context.Context) error {
				return client.RevokeLease(ctx, leaseID)
			}).
			Title("Revoking credentials...").
			Context(ctx).
			Type(spinner.Dots).
			Run(); err != nil {
			log.Fatal().Err(err).Msgf("could not revoke lease %q", leaseID)
		}

		log.Info().Msgf("Revoked lease %q", leaseID)

		if profileMatches {
			if profile.HasSession {
				log.Warn().Msg("These are STS session credentials, AWS keeps accepting them until they expire")
			}

			if err := removeAwsCredentials(profileName); err != nil {
				log.Fatal().Err(err).Msgf("could not remove credentials from profile %q", profileName)
			}
			log.Info().Msgf("Removed credentials from profile %q", profileName)
		}
	},
}

func printAwsCredentialsProfile(profile awsCredentialsProfile) {
	data := map[string]any{
		"profile":       profile.Name,
		"access_key_id": profile.AccessKeyID,
		"lease_id":      profile.LeaseID,
	}

	var problematicColumns []string
	if profile.ExpiresKnown {
		expires, parsed := reformatTimestamp(profile.Expiration.Format(time.RFC3339))
		if parsed != nil && time.Now().After(*parsed) {
			problematicColumns = append(problematicColumns, "expires")
			expires = fmt.Sprintf("expired %s", expires)
		}
		data["expires"] = expires
	} else {
		data["expires"] = "unknown"
	}

	tui.PrintMapOutput(data, problematicColumns...)
}

func init() {
	vaultAwsCmd.AddCommand(vaultAwsRevokeCredentialsCmd)

	vaultAwsRevokeCredentialsCmd.Flags().StringP(vaultAwsProfile, "p", vaultAwsDefaultProfile, "Specifies the name of the AWS credentials profile section")
	vaultAwsRevokeCredentialsCmd.Flags().StringP(vaultAwsLeaseID, "l", "", "Revoke this lease instead of the one stored in the profile")
	vaultAwsRevokeCredentialsCmd.Flags().BoolP(vaultForce, "f", false, "Skip displaying the credentials info and the confirmation prompt")
}
