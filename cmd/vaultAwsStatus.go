package cmd

import (
	"github.com/rs/zerolog/log"
	"github.com/soerenschneider/sc/pkg"
	"github.com/spf13/cobra"
)

var vaultAwsStatusCmd = &cobra.Command{
	Use:     "status",
	Aliases: []string{"expiry", "show"},
	Short:   "Show when AWS credentials generated by Vault expire",
	Long: `Show information about AWS credentials that have been generated using 'generate-credentials',
such as the access key id, the Vault lease id and when the credentials expire.

The information is read from the AWS credentials file (~/.aws/credentials), Vault is not contacted.
If no profile is given, all profiles holding credentials generated by Vault are shown.`,
	Run: func(cmd *cobra.Command, args []string) {
		profiles, err := readAwsCredentialsProfiles(pkg.GetString(cmd, vaultAwsProfile))
		if err != nil {
			log.Fatal().Err(err).Msg("could not read credentials")
		}

		if len(profiles) == 0 {
			log.Info().Msg("No credentials generated by Vault found")
			return
		}

		for _, profile := range profiles {
			printAwsCredentialsProfile(profile)
		}
	},
}

func init() {
	vaultAwsCmd.AddCommand(vaultAwsStatusCmd)

	vaultAwsStatusCmd.Flags().StringP(vaultAwsProfile, "p", "", "Only show the given AWS credentials profile section")
}
